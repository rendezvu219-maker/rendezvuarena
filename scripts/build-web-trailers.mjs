// Derived web media only: never overwrite the user's source MP4s.
// FFmpeg faststart: https://ffmpeg.org/ffmpeg-formats.html#mov_002c-mp4_002c-ismv
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';

const root = fileURLToPath(new URL('../', import.meta.url));
const inputDir = path.join(root, 'assets/trailers');
const outputDir = path.join(inputDir, 'web');
const ffmpeg = process.argv[2] || process.env.FFMPEG_PATH || 'ffmpeg';
const profile = 'h264-1080p30-crf23-max4m-aac128-faststart-v1';
fs.mkdirSync(outputDir, { recursive:true });
const manifest = {};
for (const file of fs.readdirSync(inputDir).filter(name => /^\d{4}\.mp4$/.test(name)).sort()) {
  const id = file.slice(0, 4), input = path.join(inputDir, file);
  const source = fs.readFileSync(input);
  const sourceHash = createHash('sha256').update(source).digest('hex');
  const revision = createHash('sha256').update(profile).update(source).digest('hex').slice(0, 12);
  const outputName = `${id}-${revision}.mp4`;
  const output = path.join(outputDir, outputName);
  if (!fs.existsSync(output)) {
    const temporary = path.join(outputDir, `${id}-${revision}.tmp.mp4`);
    const result = spawnSync(ffmpeg, ['-hide_banner', '-loglevel', 'error', '-y', '-i', input,
      '-map', '0:v:0', '-map', '0:a:0?', '-vf', "scale=w='min(1920,iw)':h=-2,fps=30",
      '-c:v', 'libx264', '-preset', 'fast', '-crf', '23', '-maxrate', '4M', '-bufsize', '8M',
      '-pix_fmt', 'yuv420p', '-profile:v', 'high', '-level:v', '4.1', '-g', '30', '-threads', '2',
      '-c:a', 'aac', '-b:a', '128k', '-movflags', '+faststart', '-map_metadata', '-1', temporary],
    { encoding:'utf8', maxBuffer:1024 * 1024 });
    if (result.error || result.status !== 0) throw new Error(result.error?.message || result.stderr);
    fs.renameSync(temporary, output);
  }
  const bytes = fs.statSync(output).size;
  manifest[id] = { src:`assets/trailers/web/${outputName}`, sourceHash, sourceBytes:source.length, bytes };
  console.log(`${id}: ${source.length} -> ${bytes} bytes`);
}
const posters = {};
for (const id of Object.keys(manifest)) {
  const file = ['png', 'webp', 'jpg', 'jpeg'].map(ext => `${id}.${ext}`).find(name => fs.existsSync(path.join(inputDir, name)));
  if (!file) continue;
  const source = fs.readFileSync(path.join(inputDir, file));
  const sourceHash = createHash('sha256').update(source).digest('hex');
  const revision = createHash('sha256').update('webp-q88-1080-v1').update(source).digest('hex').slice(0, 12);
  const outputName = `${id}-poster-${revision}.webp`;
  const output = path.join(outputDir, outputName);
  if (!fs.existsSync(output)) {
    const temporary = path.join(outputDir, `${id}-poster-${revision}.tmp.webp`);
    const result = spawnSync(ffmpeg, ['-hide_banner', '-loglevel', 'error', '-y', '-i', path.join(inputDir, file),
      '-frames:v', '1', '-vf', "scale=w='min(1920,iw)':h=-2", '-c:v', 'libwebp', '-quality', '88', temporary],
    { encoding:'utf8', maxBuffer:1024 * 1024 });
    if (result.error || result.status !== 0) throw new Error(result.error?.message || result.stderr);
    fs.renameSync(temporary, output);
  }
  posters[id] = { src:`assets/trailers/web/${outputName}`, sourceSrc:`assets/trailers/${file}`, sourceHash, sourceBytes:source.length, bytes:fs.statSync(output).size };
}
// Generated manifest; run this build again whenever source video or artwork changes.
fs.writeFileSync(path.join(root, 'js/trailer-assets.js'),
  `// Generated by scripts/build-web-trailers.mjs; source media stays untouched.\nexport const WEB_TRAILERS = Object.freeze(${JSON.stringify(manifest, null, 2)});\nexport const WEB_TRAILER_POSTERS = Object.freeze(${JSON.stringify(posters, null, 2)});\n`);
console.log(`Web trailers ready: ${Object.keys(manifest).length}`);
