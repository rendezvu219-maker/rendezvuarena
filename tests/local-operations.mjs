import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { LocalOperations } from '../js/local-operations.js';
import { saveTournamentDraftGame } from '../js/tournament-draft.js';
import { P2PDraftSync } from '../js/p2p-sync.js';
class MemoryStorage { constructor() { this.data = new Map(); } getItem(key) { return this.data.get(key) || null; } setItem(key,value) { this.data.set(key,String(value)); } removeItem(key) { this.data.delete(key); } }
const storage = new MemoryStorage();
const base = 'https://rendezvu219-maker.github.io/rendezvuarena/dashboard.html';
let ops = new LocalOperations({ storage, baseUrl: base });
const request = (route, body) => ops.request(route, body ? { method: 'POST', body } : {});
const created = await request('/api/tournaments', { name: 'Account-free cup' });
const id = created.tournament.id;
const dashboard = readFileSync(new URL('../dashboard.html', import.meta.url), 'utf8');
assert.match(dashboard, /<section class="ops-auth hidden" id="auth-view">/);
assert.match(dashboard, /id="btn-new-tournament" type="button"/);
assert.ok(!dashboard.includes('static-tournament-entry.js'));
for (let i = 0; i < 8; i++) await request(`/api/tournaments/${id}/teams`, { name: `Team ${i+1}` });
assert.equal((await request(`/api/tournaments/${id}/preflight`)).ok, true);
const generated = await request(`/api/tournaments/${id}/bracket/generate`, { bestOf: 3 });
assert.equal(generated.matches.length, 7);
let details = await request(`/api/tournaments/${id}`);
assert.deepEqual(details.matches.filter(match => match.round_no === 1).map(match => [match.team_a_name, match.team_b_name]), [['Team 1','Team 8'],['Team 4','Team 5'],['Team 2','Team 7'],['Team 3','Team 6']]);
assert.ok(details.teams.every(team => team.captain_user_id === null));
ops = new LocalOperations({ storage, baseUrl: base });
assert.equal((await request('/api/tournaments')).tournaments[0].name, 'Account-free cup');
await ops.request(`/api/tournaments/${id}`, { method:'PATCH', body:{ rules:{...details.tournament.rules,seriesRule:'squadra_blast',squadraBlastCarryBans:true} } });
const matches = details.matches.filter(match=>match.round_no===1);
await ops.request(`/api/matches/${matches[0].id}`, { method:'PATCH', body:{seriesRule:'squadra_blast'} });
const rooms = await Promise.all(matches.map(match=>request(`/api/matches/${match.id}/draft-room`,{linkAccess:true})));
assert.equal(new Set(rooms.map(item=>item.room.roomCode)).size,4);
for (const {room} of rooms) {
  assert.equal(room.config.operationsRoom,true);
  assert.equal(room.config.matchId,undefined,'Static rooms must not call backend APIs.');
  assert.ok(!JSON.stringify(room.config).includes('organizerToken'));
  assert.ok(!JSON.stringify(room.config).includes('tokens'));
  for (const link of Object.values(room.links)) assert.equal(new URL(link).pathname.startsWith('/rendezvuarena/'),true);
}
const room = rooms[0].room;
const result = await saveTournamentDraftGame({config:room.config,roomCode:room.roomCode,hostToken:new URLSearchParams(new URL(room.links.host).hash.slice(1)).get('access'),winnerSide:'A',sideAssignment:{A:'teamB',B:'teamA'},engine:{state:'complete',teamA:{picks:['0001'],bans:['0003']},teamB:{picks:['0002'],bans:['0004']}}},storage);
assert.equal(result.scoreA,1);
const gameTwo = await request(`/api/matches/${matches[0].id}/draft-room`,{linkAccess:true});
assert.equal(gameTwo.room.config.gameNumber,2);
assert.deepEqual(gameTwo.room.config.previousPicksA,['0002']);
assert.deepEqual(gameTwo.room.links,room.links);
const isolated = await request(`/api/matches/${matches[1].id}/draft-room`,{linkAccess:true});
assert.equal(isolated.room.config.gameNumber,1);
assert.deepEqual(isolated.room.config.previousPicksA,[]);
assert.equal((await request(`/api/tournaments/${id}`)).matches.find(match=>match.id===matches[0].id).score_a,1);
await request(`/api/matches/${matches[0].id}/results/submit`,{scoreA:2,scoreB:0});
details = await request(`/api/tournaments/${id}`);
assert.equal(details.matches.find(match=>match.id===matches[0].next_match_id).team_a_id,matches[0].team_a_id);
const stranger = new LocalOperations({ storage:new MemoryStorage(), baseUrl:base });
await assert.rejects(()=>stranger.request(`/api/tournaments/${id}`),/OPS_NOT_FOUND/);
const randomCup = (await request('/api/tournaments',{name:'Manual randomizer'})).tournament;
const preview = await request(`/api/tournaments/${randomCup.id}/manual-randomizer/preview`,{manualNames:Array.from({length:32},(_,i)=>`Player ${i+1}`),teamSize:4});
assert.ok(preview.preview.assignments.every(team=>team.members.every(member=>member.display_name && !member.isCaptain)));
await request(`/api/tournaments/${randomCup.id}/manual-randomizer/confirm`,{previewId:preview.preview.id});
assert.equal((await request(`/api/tournaments/${randomCup.id}`)).teams.length,8);
const groups = await request(`/api/tournaments/${randomCup.id}/bracket/generate-groups`,{groupCount:2,bestOf:1});
assert.equal(groups.matches.length,12);
for (const match of groups.matches) await request(`/api/matches/${match.id}/results/submit`,{scoreA:1,scoreB:0});
assert.equal((await request(`/api/tournaments/${randomCup.id}`)).groupStandings.every(group=>group.complete),true);
assert.equal((await request(`/api/tournaments/${randomCup.id}/bracket/generate-playoffs`,{topPerGroup:2,bestOf:3})).matches.filter(match=>match.stage==='playoff').length,3);
const beforeDelete = await request(`/api/tournaments/${id}`);
assert.equal((await ops.request(`/api/tournaments/${id}`,{method:'DELETE'})).recoverable,true);
let list = await request('/api/tournaments');
assert.ok(!list.tournaments.some(item=>item.id===id));
assert.equal(list.trash.find(item=>item.id===id).name,'Account-free cup');
assert.equal(list.tournaments.find(item=>item.id===randomCup.id).name,'Manual randomizer');
await assert.rejects(()=>request(`/api/tournaments/${id}`),/OPS_NOT_FOUND/);
await assert.rejects(()=>request(`/api/matches/${matches[0].id}/draft-room`,{}),/OPS_NOT_FOUND/);
assert.equal(JSON.parse(storage.getItem(`rv_tournament_room_${room.roomCode}`)).revoked,true);
const originalStorage = globalThis.localStorage;
globalThis.localStorage = storage;
try {
  const token = new URLSearchParams(new URL(room.links.host).hash.slice(1)).get('access');
  await assert.rejects(()=>new P2PDraftSync({roomCode:room.roomCode,accessToken:token,config:room.config}).connectAsHost(),/deleted|replaced/);
} finally {
  if (originalStorage === undefined) delete globalThis.localStorage;
  else globalThis.localStorage = originalStorage;
}
await request(`/api/tournaments/${id}/restore`,{});
const restored = await request(`/api/tournaments/${id}`);
assert.deepEqual(restored.teams,beforeDelete.teams);
assert.deepEqual(restored.matches,beforeDelete.matches);
assert.equal(JSON.parse(storage.getItem(`rv_tournament_room_${room.roomCode}`)).revoked,false);
assert.deepEqual((await request(`/api/matches/${matches[0].id}/draft-room`,{})).room.links,room.links);
assert.equal((await request('/api/tournaments')).trash.length,0);
console.log('Guest creation/reload, seeding, four isolated rooms, history, advancement, and recoverable delete/restore passed.');
